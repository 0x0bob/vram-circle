// Generates app/src/generated/abis.ts from the Foundry build output (out/).
// The UI never hand-writes ABIs. CI runs this after `forge build` and fails on any diff.
// Usage: node scripts/gen-abis.mjs
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const contracts = [
  ['ProjectFactory', 'src/core/ProjectFactory.sol'],
  ['ProjectVault', 'src/core/ProjectVault.sol'],
  ['FeeRouter', 'src/fees/FeeRouter.sol'],
]

const lower = (s) => s[0].toLowerCase() + s.slice(1)
let out =
  '// AUTO-GENERATED by scripts/gen-abis.mjs from the Foundry build output. Do not edit.\n' +
  '// Regenerate: forge build && node scripts/gen-abis.mjs\n'
for (const [name] of contracts) {
  const file = join(root, 'out', `${name}.sol`, `${name}.json`)
  const abi = JSON.parse(readFileSync(file, 'utf8')).abi
  out += `\nexport const ${lower(name)}Abi = ${JSON.stringify(abi, null, 2)} as const\n`
}
const target = join(root, 'app', 'src', 'generated', 'abis.ts')
mkdirSync(dirname(target), { recursive: true })
writeFileSync(target, out)
console.log(`wrote ${target}`)
